import { describe, expect, it } from "vitest";
import * as legacy from "../shared/lib/appHelpers.jsx";
import * as finance from "../shared/lib/financeHelpers.ts";
import {
  buildAccountingData,
  buildCurrencyExposureRows,
  buildInvoiceRows,
  buildInvoiceSummary,
  buildPayrollTaxCalculatorRows,
  buildTaxCalendarRows,
  buildTaxDueDate,
  getInvoiceVatRate,
  getTaxAmountByType,
} from "../shared/lib/financeHelpers.ts";
import { currentBusinessDate } from "../shared/lib/businessDate.ts";

const orders = [
  { id: "SO-1", customer: "Ali", date: "2026-11-01", amount: 118, paid: 118, paymentMethod: "Nağd" },
  { id: "SO-2", customer: "Vali", date: "2026-11-02", amount: 236, paid: 36, paymentMethod: "Nağd" },
  { id: "SO-3", customer: "Rena", date: "2026-11-03", amount: 59, paid: 0, paymentMethod: "Nağd" },
];

describe("finance helpers", () => {
  it("stays importable from appHelpers so existing callers keep working", () => {
    for (const [name, fn] of Object.entries(finance)) {
      expect((legacy as Record<string, unknown>)[name], name).toBe(fn);
    }
  });

  it("splits VAT out of gross order amounts and numbers invoices", () => {
    expect(getInvoiceVatRate()).toBe(0.18);
    expect(getInvoiceVatRate({ vatRate: 10 })).toBe(0.1);
    const rows = buildInvoiceRows({ orders, settings: { company: "Test MMC" }, invoiceSettings: { prefix: "INV" } });
    expect(rows.map((row) => [row.id, row.netAmount, row.vatAmount, row.balance, row.status])).toEqual([
      ["INV-0001", 100, 18, 0, "Ödənilib"],
      ["INV-0002", 200, 36, 200, "Qismən ödənilib"],
      ["INV-0003", 50, 9, 59, "Ödəniş gözləyir"],
    ]);
    expect(rows[0]).toMatchObject({ seller: "Test MMC", voen: "—", currency: "AZN", eTaxStatus: "E-qaimə göndərildi" });
    expect(buildInvoiceSummary(rows)).toEqual({ count: 3, total: 413, vat: 63, paid: 118, balance: 259, ready: 2 });
  });

  it("converts sales into each currency and flags volatile rates", () => {
    const rows = buildCurrencyExposureRows({
      currencyRates: [{ code: "AZN", rate: 1 }, { code: "USD", rate: 1.7, change: 0.5, status: "Stabil" }],
      orders,
      credits: [],
      cashEntries: [],
    });
    expect(rows.map((row) => [row.code, row.salesEquivalent, row.status])).toEqual([["AZN", 413, "Baza"], ["USD", 243, "Nəzarət"]]);
  });

  it("builds a balanced ledger, P&L and cash flow", () => {
    const invoices = buildInvoiceRows({ orders });
    const accounting = buildAccountingData({
      orders,
      invoices,
      credits: [],
      stock: [],
      cashEntries: [],
      openingBalance: 100,
      expenses: [
        { id: "E1", amount: 50, status: "Təsdiq edildi", category: "İcarə" },
        { id: "E2", amount: 20, status: "Təsdiq edildi", source: "HR Payroll", category: "Maaş" },
        { id: "E3", amount: 30, status: "Təsdiq gözləyir", category: "Nəqliyyat" },
      ],
    });
    expect(accounting.cashFlow).toEqual({ opening: 100, inflow: 154, outflow: 50, closing: 204, pendingOutflow: 30 });
    expect(accounting.pl).toMatchObject({ revenue: 350, vat: 63, operatingExpenses: 70 });
    expect(accounting.balance.equity).toBe(accounting.balance.assets - accounting.balance.liabilities);
    expect(accounting.journalRows.find((row) => row.id === "JR-E2")?.status).toBe("Cash təsiri yoxdur");
  });

  it("sums payroll taxes and adds automatic tax calendar items once", () => {
    const payrollTaxRows = buildPayrollTaxCalculatorRows([{ name: "Aysel", department: "IT", salary: 1000, bonus: 0 }]);
    expect(payrollTaxRows[0]).toMatchObject({ employee: "Aysel", department: "IT" });
    const invoices = buildInvoiceRows({ orders });
    const accounting = { pl: { netProfit: 1000, revenue: 5000 } };
    const sources = { invoices, payrollTaxRows, accounting };
    expect(getTaxAmountByType("ƏDV", sources)).toBe(63);
    expect(getTaxAmountByType("Mənfəət", sources)).toBe(200);
    expect(getTaxAmountByType("Sadələşdirilmiş", sources)).toBe(100);
    expect(getTaxAmountByType("Digər", sources)).toBe(0);

    const period = currentBusinessDate.slice(0, 7);
    const custom = { id: `TAX-AUTO-VAT-${period}`, type: "ƏDV", dueDate: buildTaxDueDate(20, 1), paymentStatus: "Ödənilib" };
    const rows = buildTaxCalendarRows({ taxCalendar: [custom], ...sources });
    expect(rows).toHaveLength(3);
    expect(rows[0]).toMatchObject({ status: "Ödənilib", amount: 63, autoGenerated: true });
  });
});
