import { describe, expect, it } from "vitest";
import * as legacy from "../shared/lib/appHelpers.jsx";
import * as project from "../shared/lib/projectHelpers.ts";
import * as production from "../shared/lib/productionHelpers.ts";
import { buildProjectPortfolioSource, buildProjectRoiRows, getProjectOrderCost, isDateWithinProject } from "../shared/lib/projectHelpers.ts";
import { buildProductionPlanRows } from "../shared/lib/productionHelpers.ts";

const products = [{ name: "Laptop", costPrice: 600 }];
const orders = [
  { id: "SO-1", date: "2026-11-05", amount: 1000, paid: 1000, productLines: [{ product: "Laptop", qty: 1, price: 1000 }] },
  { id: "SO-2", date: "2026-12-05", amount: 500, paid: 0, productLines: [{ product: "Mouse", qty: 2, price: 250 }] },
];
const expenses = [
  { id: "E1", date: "2026-11-10", amount: 100, status: "Təsdiq edildi", category: "Marketinq" },
  { id: "E2", date: "2026-11-11", amount: 50, status: "Təsdiq gözləyir", category: "Marketinq" },
  { id: "E3", date: "2026-11-12", amount: 70, status: "Təsdiq edildi", category: "İcarə" },
];

describe("project and production helpers", () => {
  it("stays importable from appHelpers so existing callers keep working", () => {
    for (const [name, fn] of [...Object.entries(project), ...Object.entries(production)]) {
      expect((legacy as Record<string, unknown>)[name], name).toBe(fn);
    }
  });

  it("uses saved projects or builds one automatic sales project", () => {
    const saved = [{ id: "P1" }];
    expect(buildProjectPortfolioSource(saved, orders, expenses)).toBe(saved);
    expect(buildProjectPortfolioSource([], [], [])).toEqual([]);
    const [auto] = buildProjectPortfolioSource([], orders, expenses, products);
    expect(auto).toMatchObject({ name: "Avtomatik satış layihəsi", linkedProducts: ["Laptop", "Mouse"], expenseCategories: ["Marketinq", "İcarə"], budget: 1500, autoGenerated: true });
  });

  it("checks project date ranges and order cost", () => {
    const range = { start: "2026-11-01", end: "2026-11-30" };
    expect(isDateWithinProject("2026-11-15", range)).toBe(true);
    expect(isDateWithinProject("2026-10-31", range)).toBe(false);
    expect(isDateWithinProject("2026-12-01", range)).toBe(false);
    expect(isDateWithinProject("", range)).toBe(true);
    expect(getProjectOrderCost(orders[0], new Map([["laptop", products[0]]]))).toBe(600);
    expect(getProjectOrderCost(orders[1])).toBe(340);
    expect(getProjectOrderCost({ amount: 100 })).toBe(68);
  });

  it("computes project ROI from matched orders and expenses", () => {
    const [row] = buildProjectRoiRows({
      projects: [{ id: "P1", name: "Noutbuk kampaniyası", start: "2026-11-01", end: "2026-11-30", budget: 1000, linkedProducts: ["Laptop"], expenseCategories: ["Marketinq"] }],
      orders,
      expenses,
      products,
    });
    expect(row).toMatchObject({
      orders: 1, orderIds: ["SO-1"], revenue: 1000, productCost: 600, approvedExpenseCost: 100, pendingExpenseCost: 50,
      totalCost: 700, committedCost: 750, profit: 300, roi: 30, budgetUsage: 75, collectionRate: 100, status: "Aktiv", nextAction: "Hesabat hazır",
    });
  });

  it("plans production against warehouse stock and finds the bottleneck", () => {
    const plans = [
      { id: "PR-1", product: "Masa", plannedQty: 2, salePrice: 300, laborCost: 40, materials: [{ product: "Taxta", qty: 3 }, { product: "Vint", qty: 10 }] },
      { id: "PR-2", plannedQty: 1, status: "İstehsal edildi", materials: [{ product: "Vint", qty: 50 }] },
    ];
    const warehouseStock = { "WH-1": [{ product: "Taxta", total: 10, reserved: 0, price: 20 }, { product: "Vint", total: 5, reserved: 0, price: 1 }] };
    const [open, done] = buildProductionPlanRows(plans, [], warehouseStock, [], [{ id: "WH-1", name: "Əsas anbar" }]);
    expect(open).toMatchObject({ warehouseId: "WH-1", warehouseName: "Əsas anbar", materialCost: 140, totalCost: 180, unitCost: 90, projectedProfit: 420, bottleneck: "Vint", canProduce: false, status: "Xammal riski" });
    expect(open.materials.map((material) => [material.product, material.needed, material.available, material.enough])).toEqual([["Taxta", 6, 10, true], ["Vint", 20, 5, false]]);
    expect(done).toMatchObject({ producedQty: 1, canProduce: false, bottleneck: "İstehsal bağlandı", issueStatus: "Xammal çıxıldı", status: "İstehsal edildi" });
  });
});
